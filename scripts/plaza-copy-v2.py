WORD_RE = re.compile(r"[а-яёa-z0-9]+", re.I)


def wc(s: str) -> int:
    return len(WORD_RE.findall(s.replace("{name}", "Имя")))


def main() -> None:
    cfg = json.loads(SRC.read_text())
    seqs = cfg["sequences"]
    missing = sorted(set(seqs) - set(COPY))
    extra = sorted(set(COPY) - set(seqs))
    if missing or extra:
        raise SystemExit(f"id mismatch\nmissing in COPY: {missing}\nextra in COPY: {extra}")

    violations: list[str] = []
    titles: dict[str, list[str]] = {}
    for sid, seq in seqs.items():
        block = COPY[sid]
        cues = seq.get("cues") or []
        if len(block["cues"]) != len(cues):
            raise SystemExit(f"{sid}: copy has {len(block['cues'])} cues, json has {len(cues)}")
        seq["title"] = block["title"]
        titles.setdefault(block["title"], []).append(sid)
        tw = wc(block["title"])
        if tw < 3:
            violations.append(f"{sid} title short {tw}w: {block['title']}")
        if tw > 8:
            violations.append(f"{sid} title long {tw}w: {block['title']}")
        for i, (cue, (text, tts)) in enumerate(zip(cues, block["cues"]), 1):
            cue["text"] = text
            cue["ttsText"] = tts
            cw, tws = wc(text), wc(tts)
            if cw > 10:
                violations.append(f"{sid} C{i} cap {cw}w: {text}")
            if tws > 16 and "{name}" not in tts:
                violations.append(f"{sid} C{i} tts {tws}w: {tts}")
            if tws < 5 and "{name}" not in tts:
                violations.append(f"{sid} C{i} tts short {tws}w: {tts}")
            if text.strip().lower().rstrip(".") == tts.strip().lower().rstrip(".") and "{name}" not in text:
                violations.append(f"{sid} C{i} cap==tts")

    cfg["greetingSubtitle"] = "Кисловодск, у входа в парк"
    hint = "Выберите тему — можно смотреть по очереди"
    if cfg.get("menus", {}).get("main", {}).get("menuCopy"):
        cfg["menus"]["main"]["menuCopy"]["hint"] = hint
    if cfg.get("menuCopy"):
        cfg["menuCopy"]["hint"] = hint

    DST.write_text(json.dumps(cfg, ensure_ascii=False, indent=2) + "\n")
    print("saved", DST)
    print("blocks", len(COPY), "cues", sum(len(b["cues"]) for b in COPY.values()))
    shared = {t: ids for t, ids in titles.items() if len(ids) > 1}
    if shared:
        print("shared titles:")
        for t, ids in shared.items():
            print(" ", t, ids)
    if violations:
        print("soft checks", len(violations))
        for v in violations:
            print(" ", v)
    else:
        print("no soft-check violations")


if __name__ == "__main__":
    main()
